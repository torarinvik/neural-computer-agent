"""Probe whether early learner state selects a causal replay budget.

The targets are complete matched trajectories generated by the verifier.  They
are never used as controller inputs: the probe sees only replay state before
the first update of each early experience batch.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import torch
from torch import nn

from .train import seed_everything


BASE_FEATURES = (
    "loss_before",
    "previous_loss_reduction",
    "previous_gradient_norm",
    "observed_examples",
)
FEATURES = tuple(
    f"{stat}_{name}"
    for name in BASE_FEATURES
    for stat in ("mean", "std", "first", "last", "delta")
)


def state_features(payload: dict[str, object], early_steps: int) -> torch.Tensor:
    """Summarize pre-update state without accessing downstream outcomes."""
    rows = [
        row for row in payload["replay_trace"]  # type: ignore[index]
        if row["arm"] == "composition"
        and int(row["replay_index"]) == 0
        and int(row["experience_step"]) <= early_steps
    ]
    if len(rows) != early_steps:
        raise ValueError(
            f"expected {early_steps} composition pre-update rows, got {len(rows)}")
    values: list[float] = []
    for name in BASE_FEATURES:
        series = torch.tensor([
            math.log1p(float(row[name])) if name == "observed_examples"
            else float(row[name])
            for row in rows
        ])
        values.extend((
            float(series.mean()),
            float(series.std(unbiased=False)),
            float(series[0]),
            float(series[-1]),
            float(series[-1] - series[0]),
        ))
    return torch.tensor(values, dtype=torch.float32)


def target_label(
        lower_budget: dict[str, object], higher_budget: dict[str, object],
        *, capability_tolerance: float,
) -> tuple[float, dict[str, float | bool]]:
    """Prefer extra compute only when it buys samples within a utility guard."""
    lower_history = lower_budget["histories"]["option_composition"]  # type: ignore[index]
    higher_history = higher_budget["histories"]["option_composition"]  # type: ignore[index]
    lower_utility = float(lower_history[-1]["verified_utility"])
    higher_utility = float(higher_history[-1]["verified_utility"])
    lower_bits = lower_budget["stable_target_bits"]["option_composition"]  # type: ignore[index]
    higher_bits = higher_budget["stable_target_bits"]["option_composition"]  # type: ignore[index]
    if lower_bits is None or higher_bits is None:
        raise ValueError("causal budget labels require stable mastery")
    saves_experience = int(higher_bits) < int(lower_bits)
    keeps_capability = higher_utility >= lower_utility - capability_tolerance
    return float(saves_experience and keeps_capability), {
        "lower_bits": float(lower_bits),
        "higher_bits": float(higher_bits),
        "lower_utility": lower_utility,
        "higher_utility": higher_utility,
        "saves_experience": saves_experience,
        "keeps_capability": keeps_capability,
    }


class BudgetProbe(nn.Module):
    def __init__(self, width: int, hidden: int) -> None:
        super().__init__()
        self.network = (
            nn.Linear(width, 1) if hidden == 0 else nn.Sequential(
                nn.Linear(width, hidden), nn.GELU(), nn.Linear(hidden, 1)))

    def forward(self, features: torch.Tensor) -> torch.Tensor:
        return self.network(features)


def binary_metrics(probability: torch.Tensor, target: torch.Tensor) -> dict[str, float]:
    prediction = probability.flatten() >= 0.5
    target_bool = target.flatten().bool()
    return {
        "accuracy": float((prediction == target_bool).float().mean()),
        "positive_rate": float(target.float().mean()),
        "predicted_positive_rate": float(prediction.float().mean()),
        "brier": float((probability.flatten() - target.flatten()).square().mean()),
    }


def load_examples(
        report_dir: Path, seeds: list[int], *, lower_budget: int,
        higher_budget: int, early_steps: int,
        capability_tolerance: float,
) -> tuple[torch.Tensor, torch.Tensor, list[dict[str, float | bool | int]]]:
    features, targets, metadata = [], [], []
    for seed in seeds:
        state = json.loads((report_dir / f"u40_{seed}.json").read_text())
        lower = json.loads(
            (report_dir / f"u{lower_budget}_{seed}.json").read_text())
        higher = json.loads(
            (report_dir / f"u{higher_budget}_{seed}.json").read_text())
        label, details = target_label(
            lower, higher, capability_tolerance=capability_tolerance)
        features.append(state_features(state, early_steps))
        targets.append(label)
        metadata.append({"seed": seed, "label": bool(label), **details})
    return (
        torch.stack(features),
        torch.tensor(targets, dtype=torch.float32)[:, None],
        metadata,
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--report-dir", type=Path, required=True)
    parser.add_argument("--train-seed", type=int, action="append", required=True)
    parser.add_argument("--test-seed", type=int, action="append", required=True)
    parser.add_argument("--lower-budget", type=int, default=48)
    parser.add_argument("--higher-budget", type=int, default=56)
    parser.add_argument("--early-steps", type=int, default=8)
    parser.add_argument("--capability-tolerance", type=float, default=0.003)
    parser.add_argument("--hidden", type=int, default=0)
    parser.add_argument("--steps", type=int, default=600)
    parser.add_argument("--learning-rate", type=float, default=0.02)
    parser.add_argument("--seed", type=int, default=8260)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--device", default=("cuda" if torch.cuda.is_available() else "cpu"))
    args = parser.parse_args()
    if args.hidden < 0:
        raise ValueError("hidden width must be non-negative")
    seed_everything(args.seed)
    device = torch.device(args.device)
    train_x, train_y, train_metadata = load_examples(
        args.report_dir, args.train_seed, lower_budget=args.lower_budget,
        higher_budget=args.higher_budget, early_steps=args.early_steps,
        capability_tolerance=args.capability_tolerance)
    test_x, test_y, test_metadata = load_examples(
        args.report_dir, args.test_seed, lower_budget=args.lower_budget,
        higher_budget=args.higher_budget, early_steps=args.early_steps,
        capability_tolerance=args.capability_tolerance)
    mean = train_x.mean(0, keepdim=True)
    scale = train_x.std(0, keepdim=True).clamp_min(1e-6)
    train_x = ((train_x - mean) / scale).to(device)
    test_x = ((test_x - mean) / scale).to(device)
    train_y, test_y = train_y.to(device), test_y.to(device)
    model = BudgetProbe(len(FEATURES), args.hidden).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate,
                                  weight_decay=0.05)
    generator = torch.Generator(device=device).manual_seed(args.seed + 1)
    for _ in range(args.steps):
        indices = torch.randint(0, train_x.shape[0],
                                (min(16, train_x.shape[0]),),
                                generator=generator, device=device)
        logits = model(train_x[indices])
        loss = nn.functional.binary_cross_entropy_with_logits(
            logits, train_y[indices])
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()
    with torch.no_grad():
        train_probability = torch.sigmoid(model(train_x))
        test_probability = torch.sigmoid(model(test_x))
        shuffled = test_y[torch.randperm(
            test_y.shape[0], generator=generator, device=device)]
        shuffled_features = test_x[:, torch.randperm(
            test_x.shape[1], generator=generator, device=device)]
        shuffled_feature_probability = torch.sigmoid(model(shuffled_features))
    held_out = binary_metrics(test_probability, test_y)
    shuffled_metrics = binary_metrics(test_probability, shuffled)
    shuffled_feature_metrics = binary_metrics(shuffled_feature_probability, test_y)
    report = {
        "schema": "causal-budget-probe-v1",
        "configuration": {
            "lower_budget": args.lower_budget,
            "higher_budget": args.higher_budget,
            "early_steps": args.early_steps,
            "capability_tolerance": args.capability_tolerance,
            "hidden": args.hidden,
            "features": FEATURES,
        },
        "train_metadata": train_metadata,
        "test_metadata": test_metadata,
        "train": binary_metrics(train_probability, train_y),
        "held_out": held_out,
        "shuffled_label_control": shuffled_metrics,
        "shuffled_feature_control": shuffled_feature_metrics,
        "gate": {
            "held_out_accuracy_at_least_75": held_out["accuracy"] >= 0.75,
            "held_out_beats_shuffled_by_20_points": (
                held_out["accuracy"] >= shuffled_metrics["accuracy"] + 0.20),
            "feature_shuffle_degrades_by_20_points": (
                held_out["accuracy"] >= shuffled_feature_metrics["accuracy"] + 0.20),
            "both_classes_in_held_out": 0 < held_out["positive_rate"] < 1,
        },
    }
    report["gate"]["accepted_for_allocator"] = all(report["gate"].values())
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
