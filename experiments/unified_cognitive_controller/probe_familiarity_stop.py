"""Learn whether one consolidation pass is already sufficient.

The policy sees only the controller's sensory latent summary and optimization
statistics after its first pass.  Its target is generated by two independent
high-precision verifier streams.  It never sees the contour blend, task name,
correct unattempted action, or generator state.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import random

import torch
from torch import nn


SCALAR_FEATURES = (
    "new_batch_accuracy",
    "skill_loss",
    "retention_loss",
    "locality",
    "total_loss",
)


def _flatten_diagnostics(value) -> tuple[float, ...]:
    """Flatten a stable, task-agnostic diagnostic mapping."""
    if value is None:
        return ()
    flattened = []
    for key in sorted(value):
        item = value[key]
        if isinstance(item, list):
            flattened.extend(float(element) for element in item)
        else:
            flattened.append(float(item))
    return tuple(flattened)


@dataclass(frozen=True)
class FamiliarityObservation:
    stream: str
    scalar_features: tuple[float, ...]
    sensory_features: tuple[float, ...]
    stable_after_one: bool
    # Private metadata is retained only to audit split coverage.  It is never
    # passed into the probe.
    verifier_blend: float


class FamiliarityProbe(nn.Module):
    def __init__(self, width: int, hidden: int = 8) -> None:
        super().__init__()
        self.network = nn.Sequential(
            nn.Linear(width, hidden),
            nn.Tanh(),
            nn.Linear(hidden, 1),
        )

    def forward(self, features: torch.Tensor) -> torch.Tensor:
        return self.network(features).squeeze(-1)


@dataclass
class Projection:
    mean: torch.Tensor
    scale: torch.Tensor
    components: torch.Tensor

    def apply(self, values: torch.Tensor) -> torch.Tensor:
        normalized = (values - self.mean) / self.scale
        return normalized @ self.components.T


def _audit_mastery(path: Path) -> bool:
    payload = json.loads(path.read_text())
    if payload.get("schema") != "pair-magnitude-compute-audit-v1":
        raise ValueError(f"unsupported audit schema: {path}")
    return bool(payload["results"]["0"]["mastery"])


def load_observations(
        root: Path, *, audit_suffixes: tuple[str, ...],
        ) -> list[FamiliarityObservation]:
    if len(audit_suffixes) < 2:
        raise ValueError("stable labels require two independent audits")
    observations = []
    for path in sorted(root.glob("*_train.json")):
        payload = json.loads(path.read_text())
        if payload.get("schema") != "pair-magnitude-appearance-bridge-v1":
            continue
        tag = path.name.removesuffix("_train.json")
        audit_paths = [root / f"{tag}_{suffix}.json"
                       for suffix in audit_suffixes]
        if not all(candidate.exists() for candidate in audit_paths):
            continue
        history = payload.get("history")
        if not isinstance(history, list) or not history:
            raise ValueError(f"missing optimization history: {path}")
        row = history[-1]
        sensory = tuple(float(value) for value in row["sensory_summary"])
        if not sensory:
            raise ValueError("empty sensory summary")
        configuration = payload["configuration"]
        observations.append(FamiliarityObservation(
            stream=str(int(configuration["seed"])),
            scalar_features=tuple(
                float(row[name]) for name in SCALAR_FEATURES)
            + _flatten_diagnostics(row.get("learner_diagnostics")),
            sensory_features=sensory,
            stable_after_one=all(
                _audit_mastery(candidate) for candidate in audit_paths),
            verifier_blend=float(configuration["blend_end"]),
        ))
    if len(observations) < 6:
        raise ValueError("fewer than six fully audited streams")
    sensory_widths = {len(row.sensory_features) for row in observations}
    scalar_widths = {len(row.scalar_features) for row in observations}
    if len(sensory_widths) != 1 or len(scalar_widths) != 1:
        raise ValueError("mixed learner-visible feature widths")
    return observations


def _raw(
        observations: list[FamiliarityObservation], *,
        feature_set: str,
        ) -> torch.Tensor:
    if feature_set == "scalar":
        values = [row.scalar_features for row in observations]
    elif feature_set == "sensory":
        values = [row.sensory_features for row in observations]
    elif feature_set == "combined":
        values = [
            (*row.scalar_features, *row.sensory_features)
            for row in observations]
    else:
        raise ValueError("unknown familiarity feature set")
    return torch.tensor(values, dtype=torch.float32)


def fit_projection(
        values: torch.Tensor, *, rank: int,
        ) -> Projection:
    mean = values.mean(dim=0)
    scale = values.std(dim=0, unbiased=False).clamp_min(1e-6)
    normalized = (values - mean) / scale
    maximum_rank = min(
        rank, normalized.shape[0] - 1, normalized.shape[1])
    if maximum_rank < 1:
        raise ValueError("projection rank collapsed")
    _, _, components = torch.linalg.svd(
        normalized, full_matrices=False)
    return Projection(
        mean=mean, scale=scale,
        components=components[:maximum_rank])


def train_probe(
        train: list[FamiliarityObservation], *, seed: int,
        feature_set: str, rank: int, hidden: int, updates: int,
        shuffled_labels: bool = False,
        ) -> tuple[FamiliarityProbe, Projection]:
    torch.manual_seed(seed)
    raw = _raw(train, feature_set=feature_set)
    projection = fit_projection(raw, rank=rank)
    features = projection.apply(raw)
    labels = torch.tensor(
        [float(row.stable_after_one) for row in train])
    if shuffled_labels:
        labels = labels[torch.randperm(labels.numel())]
    positives = float(labels.sum())
    negatives = float(labels.numel() - labels.sum())
    if positives == 0 or negatives == 0:
        raise ValueError("training fold contains only one policy class")
    model = FamiliarityProbe(features.shape[1], hidden=hidden)
    optimizer = torch.optim.AdamW(
        model.parameters(), lr=0.01, weight_decay=1e-2)
    positive_weight = torch.tensor(negatives / positives)
    for _ in range(updates):
        logits = model(features)
        loss = nn.functional.binary_cross_entropy_with_logits(
            logits, labels, pos_weight=positive_weight)
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()
    return model.eval(), projection


@torch.no_grad()
def probabilities(
        model: FamiliarityProbe, projection: Projection,
        observations: list[FamiliarityObservation], *,
        feature_set: str,
        ) -> list[float]:
    values = projection.apply(_raw(
        observations, feature_set=feature_set))
    return torch.sigmoid(model(values)).tolist()


def calibrate_threshold(
        observations: list[FamiliarityObservation],
        predicted: list[float],
        ) -> float:
    """Maximize safe stops on training data; false stops are forbidden."""
    safe = []
    for threshold_index in range(50, 100):
        threshold = threshold_index / 100
        stopped = [
            row for row, probability in zip(
                observations, predicted, strict=True)
            if probability >= threshold]
        if stopped and all(row.stable_after_one for row in stopped):
            safe.append((-len(stopped), threshold))
    return min(safe)[1] if safe else 1.0


def _metrics(
        observations: list[FamiliarityObservation],
        predicted: list[float], *, threshold: float,
        ) -> dict[str, float | int | bool]:
    stops = [
        row for row, probability in zip(
            observations, predicted, strict=True)
        if probability >= threshold]
    false_stops = sum(not row.stable_after_one for row in stops)
    saved_updates = len(stops) * 7
    return {
        "streams": len(observations),
        "one_pass_stops": len(stops),
        "false_stops": false_stops,
        "all_stops_safe": false_stops == 0,
        "stop_rate": len(stops) / len(observations),
        "mean_budget_if_continue_uses_8": (
            (len(stops) + (len(observations) - len(stops)) * 8)
            / len(observations)),
        "consolidation_updates_saved_vs_fixed_8": saved_updates,
        "fraction_updates_saved_vs_fixed_8":
            saved_updates / (len(observations) * 8),
    }


def cross_validate(
        observations: list[FamiliarityObservation], *, seed: int,
        folds: int, feature_set: str, rank: int, hidden: int,
        updates: int, shuffled_labels: bool = False,
        ) -> dict[str, object]:
    shuffled = list(observations)
    random.Random(seed).shuffle(shuffled)
    fold_rows = [shuffled[index::folds] for index in range(folds)]
    heldout_rows: list[FamiliarityObservation] = []
    heldout_probabilities: list[float] = []
    reports = []
    for index, heldout in enumerate(fold_rows):
        heldout_ids = {row.stream for row in heldout}
        train = [row for row in observations
                 if row.stream not in heldout_ids]
        model, projection = train_probe(
            train, seed=seed + index, feature_set=feature_set,
            rank=rank, hidden=hidden, updates=updates,
            shuffled_labels=shuffled_labels)
        train_probabilities = probabilities(
            model, projection, train, feature_set=feature_set)
        threshold = calibrate_threshold(train, train_probabilities)
        predicted = probabilities(
            model, projection, heldout, feature_set=feature_set)
        heldout_rows.extend(heldout)
        heldout_probabilities.extend(predicted)
        reports.append({
            "fold": index,
            "threshold": threshold,
            "heldout_streams": [row.stream for row in heldout],
            "heldout_blends_for_audit_only": sorted({
                row.verifier_blend for row in heldout}),
            "metrics": _metrics(
                heldout, predicted, threshold=threshold),
        })
    # Each fold has its own calibrated threshold, so aggregate fold metrics
    # rather than applying one new threshold to concatenated probabilities.
    aggregate = {
        "streams": len(observations),
        "one_pass_stops": sum(
            int(report["metrics"]["one_pass_stops"])
            for report in reports),
        "false_stops": sum(
            int(report["metrics"]["false_stops"])
            for report in reports),
    }
    aggregate["all_stops_safe"] = aggregate["false_stops"] == 0
    aggregate["stop_rate"] = (
        aggregate["one_pass_stops"] / aggregate["streams"])
    aggregate["mean_budget_if_continue_uses_8"] = (
        (aggregate["one_pass_stops"]
         + (aggregate["streams"] - aggregate["one_pass_stops"]) * 8)
        / aggregate["streams"])
    aggregate["fraction_updates_saved_vs_fixed_8"] = (
        aggregate["one_pass_stops"] * 7
        / (aggregate["streams"] * 8))
    return {"folds": reports, "aggregate": aggregate}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument(
        "--audit-suffixes", default="target16k,target16k_b")
    parser.add_argument("--seed", type=int, default=21980)
    parser.add_argument("--folds", type=int, default=3)
    parser.add_argument(
        "--feature-set", choices=("scalar", "sensory", "combined"),
        default="combined")
    parser.add_argument("--rank", type=int, default=8)
    parser.add_argument("--hidden", type=int, default=8)
    parser.add_argument("--updates", type=int, default=1000)
    args = parser.parse_args()
    suffixes = tuple(
        value for value in args.audit_suffixes.split(",") if value)
    observations = load_observations(
        args.root, audit_suffixes=suffixes)
    normal = cross_validate(
        observations, seed=args.seed, folds=args.folds,
        feature_set=args.feature_set, rank=args.rank,
        hidden=args.hidden, updates=args.updates)
    scalar = cross_validate(
        observations, seed=args.seed, folds=args.folds,
        feature_set="scalar", rank=args.rank,
        hidden=args.hidden, updates=args.updates)
    shuffled = cross_validate(
        observations, seed=args.seed, folds=args.folds,
        feature_set=args.feature_set, rank=args.rank,
        hidden=args.hidden, updates=args.updates,
        shuffled_labels=True)
    metrics = normal["aggregate"]
    accepted = (
        bool(metrics["all_stops_safe"])
        and float(metrics["stop_rate"]) >= 0.20
        and (
            int(shuffled["aggregate"]["false_stops"]) > 0
            or float(shuffled["aggregate"]["stop_rate"])
            < float(metrics["stop_rate"])))
    report = {
        "schema": "familiarity-consolidation-stop-probe-v1",
        "claim_boundary": (
            "The passive probe sees only the controller's sensory latent "
            "summary and learner-visible optimization statistics. Stable "
            "targets require two independent verifier streams. Blend is "
            "retained only for split auditing and is never a feature."),
        "audit_suffixes": suffixes,
        "streams": len(observations),
        "stable_after_one": sum(
            row.stable_after_one for row in observations),
        "normal": normal,
        "scalar_only_ablation": scalar,
        "shuffled_label_control": shuffled,
        "gate": {
            "no_heldout_false_stops": metrics["all_stops_safe"],
            "heldout_stop_rate_at_least_20_percent":
                float(metrics["stop_rate"]) >= 0.20,
            "shuffled_control_worse": (
                int(shuffled["aggregate"]["false_stops"]) > 0
                or float(shuffled["aggregate"]["stop_rate"])
                < float(metrics["stop_rate"])),
            "accepted_for_prospective_test": accepted,
        },
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({
        "streams": report["streams"],
        "stable_after_one": report["stable_after_one"],
        "stop_rate": metrics["stop_rate"],
        "false_stops": metrics["false_stops"],
        "fraction_updates_saved":
            metrics["fraction_updates_saved_vs_fixed_8"],
        "accepted_for_prospective_test": accepted,
    }, sort_keys=True))


if __name__ == "__main__":
    main()
